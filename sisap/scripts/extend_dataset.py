def main() -> None:
    with open(DATASET_PATH, "r", encoding="utf-8") as fh:
        dataset = json.load(fh)

    existing_ids = {s["id"] for s in dataset["standards"]}
    added = [s for s in NEW_STANDARDS if s["id"] not in existing_ids]

    dataset["standards"].extend(added)

    with open(DATASET_PATH, "w", encoding="utf-8") as fh:
        json.dump(dataset, fh, indent=2, ensure_ascii=False)
        fh.write("\n")

    categories = {}
    for std in dataset["standards"]:
        categories[std["category"]] = categories.get(std["category"], 0) + 1

    print(f"Added {len(added)} standards. Total: {len(dataset['standards'])}")
    for cat, count in sorted(categories.items()):
        print(f"  {cat:<22} {count}")


if __name__ == "__main__":
    main()
